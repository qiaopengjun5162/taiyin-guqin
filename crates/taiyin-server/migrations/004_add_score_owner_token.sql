-- 曲谱所有权凭证（发布者 token）。
--
-- 背景：`/api/v1/scores` 是无账号的共享池，原先任何人拿到 id 就能 PUT/DELETE
-- 任何一首谱——而分享链接里正好带着 id，等于「谁看见链接谁就能删」。
--
-- 不做账号体系（注册/登录/密码），改用「本机持有的随机凭证」：
-- 首次发布时前端生成一个 token 一并提交，之后改 / 删都要带同一个 token。
-- 这不是身份认证，而是**所有权凭证**：拿到 token 的人就能改删，所以要当密码对待。
--
-- 可空：迁移前的老数据没有凭证（无主谱）。无主谱一律拒绝改删，
-- 只能由管理员直接操作数据库清理——避免为了兼容老数据而留一个「谁都能删」的口子。
ALTER TABLE scores ADD COLUMN IF NOT EXISTS owner_token TEXT;
